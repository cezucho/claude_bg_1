"""Converts a frame-sequence character pack (e.g. CraftPix chibi packs: one folder of PNGs per animation)
into compact sprite sheets for the prototypes and for Godot.

For each game state (idle, move, attack, cast, hit, death) it takes one source animation folder, crops every frame
to one shared box (so the feet never jump between animations), scales it down, and writes:
  <out>/<state>.png          one horizontal strip per state
  <out>/anim.json            frame size, frame counts, fps, loop flags, foot anchor, body height
  <out>/anim.js              the same data as a script (window.ANIM_SETS[id] = ...), so a page opened from disk can load it
  <out>/<id>_frames.tres     a Godot 4 SpriteFrames resource (AtlasTexture regions into the strips)
  <out>/preview.gif          every state in a row, for a quick look

Usage:
  python sprite_pack.py --src "<pack>/PNG/PNG Sequences" --id reaper --out <dir> \
      --map idle=Idle move=Running attack=Slashing cast="Slashing in The Air" hit=Hurt death=Dying \
      [--height 220] [--fps idle=12 move=18 ...] [--res-path res://assets/characters/reaper]
"""
import argparse, glob, json, os
import numpy as np
from PIL import Image

DEFAULT_FPS = {"idle": 12, "move": 18, "attack": 20, "cast": 18, "hit": 20, "death": 15}
LOOPS = {"idle": True, "move": True}


def frames_of(folder):
    fs = sorted(glob.glob(os.path.join(folder, "*.png")))
    if not fs:
        raise SystemExit(f"no PNG frames in {folder}")
    return [Image.open(f).convert("RGBA") for f in fs]


def bbox(im, thr=8):
    a = np.asarray(im)[..., 3]
    ys, xs = np.where(a > thr)
    return (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1) if len(xs) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="folder holding one sub-folder of PNG frames per animation")
    ap.add_argument("--id", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--map", nargs="+", required=True, help="state=SourceFolder pairs")
    ap.add_argument("--fps", nargs="*", default=[], help="state=fps overrides")
    ap.add_argument("--height", type=int, default=220, help="output height of the idle body in px")
    ap.add_argument("--res-path", default=None, help="res:// folder the sheets will live in, for the Godot .tres")
    a = ap.parse_args()

    mapping = dict(kv.split("=", 1) for kv in a.map)
    fps = {**DEFAULT_FPS, **{k: float(v) for k, v in (kv.split("=", 1) for kv in a.fps)}}
    src = {st: frames_of(os.path.join(a.src, folder)) for st, folder in mapping.items()}

    # one shared crop box over every frame of every state
    boxes = [b for fr in src.values() for im in fr if (b := bbox(im))]
    x0 = min(b[0] for b in boxes); y0 = min(b[1] for b in boxes); x1 = max(b[2] for b in boxes); y1 = max(b[3] for b in boxes)
    pad = 4; x0 -= pad; y0 -= pad; x1 += pad; y1 += pad
    # the body: the idle frames' box (the foot line is its bottom, the anchor x its centre)
    ib = [bbox(im) for im in src.get("idle", next(iter(src.values())))]
    bx0 = np.median([b[0] for b in ib]); bx1 = np.median([b[2] for b in ib]); by0 = min(b[1] for b in ib); by1 = max(b[3] for b in ib)
    scale = a.height / (by1 - by0)
    fw, fh = round((x1 - x0) * scale), round((y1 - y0) * scale)

    os.makedirs(a.out, exist_ok=True)
    meta = {"id": a.id, "frameW": fw, "frameH": fh, "anchorX": round(((bx0 + bx1) / 2 - x0) * scale, 1),
            "anchorY": round((by1 - y0) * scale, 1), "bodyH": a.height, "facing": "right", "states": {}}
    strips = {}
    for st, fr in src.items():
        sheet = Image.new("RGBA", (fw * len(fr), fh))
        for i, im in enumerate(fr):
            sheet.paste(im.crop((x0, y0, x1, y1)).resize((fw, fh), Image.LANCZOS), (i * fw, 0))
        sheet.save(os.path.join(a.out, f"{st}.png"), optimize=True)
        strips[st] = sheet
        meta["states"][st] = {"file": f"{st}.png", "frames": len(fr), "fps": fps.get(st, 15), "loop": LOOPS.get(st, False),
                              "source": mapping[st]}
    json.dump(meta, open(os.path.join(a.out, "anim.json"), "w"), indent=1)
    open(os.path.join(a.out, "anim.js"), "w").write(
        f"// generated by tools/asset_gen/sprite_pack.py\nwindow.ANIM_SETS = window.ANIM_SETS || {{}};\n"
        f"window.ANIM_SETS[{json.dumps(a.id)}] = {json.dumps(meta)};\n")

    # Godot 4 SpriteFrames: one ext_resource per strip, one AtlasTexture per frame
    res = (a.res_path or f"res://{a.id}").rstrip("/")
    ext, subs, anims, n = [], [], [], 0
    for i, (st, m) in enumerate(meta["states"].items(), 1):
        ext.append(f'[ext_resource type="Texture2D" path="{res}/{m["file"]}" id="{i}_{st}"]')
        frs = []
        for f in range(m["frames"]):
            n += 1
            subs.append(f'[sub_resource type="AtlasTexture" id="AtlasTexture_{n}"]\natlas = ExtResource("{i}_{st}")\n'
                        f'region = Rect2({f * fw}, 0, {fw}, {fh})')
            frs.append(f'{{"duration": 1.0, "texture": SubResource("AtlasTexture_{n}")}}')
        anims.append(f'{{"frames": [{", ".join(frs)}], "loop": {"true" if m["loop"] else "false"}, '
                     f'"name": &"{st}", "speed": {float(m["fps"])}}}')
    tres = [f'[gd_resource type="SpriteFrames" load_steps={len(ext) + n + 1} format=3]', ""] + ext + [""] + \
           ["\n".join([s, ""]) for s in subs] + ["[resource]", f"animations = [{', '.join(anims)}]", ""]
    open(os.path.join(a.out, f"{a.id}_frames.tres"), "w").write("\n".join(tres))

    # preview: every state side by side, looping together
    cell = (fw // 2, fh // 2); longest = max(m["frames"] for m in meta["states"].values())
    gif = []
    for f in range(longest):
        canvas = Image.new("RGBA", (cell[0] * len(strips), cell[1]), (46, 52, 64, 255))
        for j, (st, sheet) in enumerate(strips.items()):
            m = meta["states"][st]; k = f % m["frames"] if m["loop"] else min(f, m["frames"] - 1)
            fr = sheet.crop((k * fw, 0, (k + 1) * fw, fh)).resize(cell, Image.LANCZOS)
            canvas.alpha_composite(fr, (j * cell[0], 0))
        gif.append(canvas.convert("RGB"))
    gif[0].save(os.path.join(a.out, "preview.gif"), save_all=True, append_images=gif[1:], duration=66, loop=0)
    print(json.dumps({k: v for k, v in meta.items() if k != "states"}), {k: v["frames"] for k, v in meta["states"].items()})


if __name__ == "__main__":
    main()
